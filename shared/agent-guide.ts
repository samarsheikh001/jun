const AGENTS_GUIDE = `${HEADER}

# Guide for coding agents: a Jun support agent

This folder is the configuration of a **Jun support agent**: the AI that answers customers in a
company's website chat, and hands over to the company's team. The files are its config, pulled from
the company's Jun desk with the \`jun\` CLI. Nothing here runs locally: the desk checks the files,
stores each push as a version and runs them.

**These instructions are for you, the coding agent.** The support AI's own persona and rules are in
\`instructions.md\`: edit that file to change how it talks to customers. Don't add rules for the
support AI here, and don't edit this file, \`CLAUDE.md\` or \`README.md\`: \`jun pull\` overwrites them.

## The loop

The CLI talks to the desk with an API token: \`jun login <desk-url>\` (a token from the desk's
Settings → Developer → API tokens), or \`JUN_DESK_URL\` and \`JUN_DESK_TOKEN\` in the environment.

1. Edit the files (formats below).
2. Test: \`jun eval .\` runs \`tests/*.yaml\` and replays recent real conversations against the
   folder. Without \`--mock-tools\` it calls the real APIs, so use it whenever an action changes
   something (each action's \`mock:\` is returned instead); \`--sample 0\` skips the replay. In a checkout of the Jun repo the CLI is \`npm run jun -- eval <folder>\`.
3. Fix what fails. A config error names the file and key; nothing runs until it's fixed.
4. Make it live: \`jun push . -m "what changed"\`. The desk validates again and saves a new version.
   If push reports that someone edited the agent on the desk since the last pull, run \`jun pull .\`,
   merge (git), then push again. Never use \`--force\` unless the person asks for it.

Don't push or run evals against a desk without the person's go-ahead: a push goes live for customers.

${FILE_FORMAT}

${HARD_RULES}

${MORE}
`;

