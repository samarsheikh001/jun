/** The file format, every file and key: AGENTS.md's middle, and the MCP's `jun://guide/files` resource. */
export const FILE_FORMAT = `## Files

\`\`\`text
instructions.md         required: persona, tone, rules (+ guardrail frontmatter)
tasks/<name>.md         procedures for one job each
actions/<name>.yaml     HTTP requests the AI may make (.yml works too)
widgets/<name>.widget   cards a result is shown as (ChatKit widget JSON)
tests/<name>.yaml       test cases for jun eval (.yml works too)
website-actions.yaml    optional: how actions on the customer's website run
desk.yaml               optional: the desk's settings
\`\`\`

Any other path is an error, except these generated guide files and \`.jun-version\` (the version
last pulled; leave it). Names: tasks lowercase letters/digits joined by \`-\` (\`change-plan\`);
actions start with a letter, then lowercase letters, digits, \`_\` (\`lookup_order\`); widgets start
with a letter, then lowercase letters, digits, \`_\`, \`-\`; tests letters, digits, \`_\`, \`-\`.
Limits: 200 files, 256 KB in total, 20 actions, 20 widgets. Unknown keys are errors (task frontmatter and
widget files allow extra keys).

### instructions.md

Markdown body: how the AI talks to customers and what it must and mustn't do. Optional frontmatter,
only these keys:

\`\`\`markdown
---
maxReplies: 8          # AI replies per conversation before a person takes over (1-50, default 8)
handoffTopics:         # always hand these to a person (plain words, up to 30)
  - legal or security questions
---
# How to talk to customers
- Be friendly, concise and specific.
\`\`\`

\`@lookup_order\` in the body names the action \`actions/lookup_order.yaml\`.

### tasks/<name>.md

A procedure. Frontmatter \`description\` (required, at most 1024 characters) says when it applies;
the body (required) is the steps. \`name\`, if given, must equal the file name. Name an action with
\`@action_name\` in a step. Before an action that changes something, write "say exactly what changes
and wait for a clear yes": actions have no confirm setting of their own.

Optional intent keys (the customer's app opens a chat for this purpose with
\`JunDesk.open({ intent, onExit })\`): \`intent\` (lowercase letters, digits, \`_\`, \`-\`, at most 40;
one task per intent), \`opening\` (first line, one line, at most 300), \`replies\` (quick replies, at
most 8, each at most 60; needs \`opening\`), \`exit\` (a button label always on screen, at most 40).
\`opening\`, \`replies\` and \`exit\` need \`intent\`.

\`\`\`markdown
---
description: The customer asks for a refund or their money back.
---
1. Ask for the order number if they haven't given it.
2. Look it up with @lookup_order.
3. Hand off to a person with the order number in the reason.
\`\`\`

### actions/<name>.yaml

One HTTP request the AI may call. Keys:

- \`description\` (required): what it returns and when to use it; the AI decides from this.
- \`method\`: \`GET\` (default) or \`POST\`.
- \`url\`: \`https://…\` with \`{input}\` placeholders. Required unless the action only shows its \`widget\`.
- \`headers\`, \`query\`: maps of strings, with placeholders.
- \`body\`: JSON body, \`POST\` only. A value that is exactly \`"{name}"\` keeps the input's type.
  Without \`body\`, a POST sends the inputs as a JSON object.
- \`input\`: map of name (letters, digits, \`_\`) to \`{ type, description, required, enum }\`, or just a
  type. Types: \`string\` (default), \`number\`, \`integer\`, \`boolean\`. \`required\` defaults to true.
- \`pick\`: list of top-level response fields the AI sees.
- \`mock\`: canned response for \`jun eval --mock-tools\`.
- \`status\`: the one line the customer sees while it runs (plain text, at most 60 characters, no
  placeholders; default "Looking that up").
- \`pages\`: offer it only on these page paths (\`/pricing\`, \`/orders/*\`).
- \`widget\`: show a successful result as \`widgets/<name>.widget\` (the file must exist).
- \`widget_done\`, \`widget_failed\`: when a widget's button ran this action, the line the card shows
  (a Jinja template over the entered values and the result, at most 200 characters).

Placeholders: \`{input}\`; the signed-in customer \`{user.id}\`, \`{user.email}\`, \`{user.name}\`,
\`{user.<attribute>}\`; a workspace key \`{secrets.NAME}\` (headers only); the customer's own key
\`{user.secrets.NAME}\` (headers only). Key names are UPPER_SNAKE_CASE. Reserved action names:
\`handoff\`, \`flag_problem\`, \`jun_done\`, \`show_widget\`, \`activate_skill\`.

\`\`\`yaml
description: Look up an order by its number. Returns status, order date and total.
status: Checking your order
url: https://api.example.com/orders/{orderNumber}
headers:
  Authorization: Bearer {secrets.ACME_API_KEY}
input:
  orderNumber: { type: string, description: The order number, like A-1042 }
pick: [status, orderedOn, total]
mock: { status: delivered, orderedOn: "2026-09-02", total: "$49.00" }
\`\`\`

### widgets/<name>.widget

A card in OpenAI's ChatKit widget format (what ChatKit Studio's Download gives). JSON:

- \`version\` (required): \`"1.0"\`.
- \`template\` (required): a Jinja template that renders the card's component tree as JSON. Its data is
  the action's JSON response (an object as is, a list as \`items\`). Write values with \`| tojson\`.
- \`name\`: title on the desk. \`summary\`: one-line Jinja template (at most 200 characters).
- \`sample\`: example data; the template must render with it. \`jsonSchema\`: the data's JSON Schema;
  \`sample\` and \`states\` must fit it. \`states\`: up to 10 \`{ name, data }\` examples.
- \`aiFill: true\`: the AI may show the card with data it fills in (needs \`sample\`).
- \`pageActions\`: website actions whose result this card shows (up to 10).

The rendered root is a \`Card\`, \`ListView\` or \`Basic\`; at most 400 components, 48 KB. Button
\`onClickAction.type\`: \`tool:<name>\` runs \`actions/<name>.yaml\`; \`page:<name>\` a website action;
\`open_url\` opens \`payload.url\`; \`dismiss\` folds the card; anything else is sent to the AI as the
customer's choice. The Jinja is a subset (no eval); see the docs for filters and components.

### tests/<name>.yaml

A YAML list of cases:

\`\`\`yaml
- name: refund goes to a person
  message: I want my money back for order A-1042     # or messages: [..., ...]
  expect:
    outcome: handoff        # answer | handoff | escalate | action
    tools: [lookup_order]   # actions it must call
    criteria: Asks for nothing it already has.   # checked by a judge model
\`\`\`

Case keys: \`name\`, \`message\` or \`messages\`, \`intent\`, \`page\` (\`/pricing\`), \`actions\` (website
actions on the page: \`name\`, \`description\`, \`inputSchema\`, \`risk\`, \`context\`, \`key\`,
\`annotations\`, \`mock\`), \`expect\` (\`outcome\`, \`tools\`, \`criteria\`, \`action\` (a name or
\`{ name, input }\`), \`widget\`).

### website-actions.yaml

How each action registered by the customer's website runs: a map of action name to \`auto\`,
\`confirm\` or \`human\`, or to \`{ run, status }\` (\`status\`: one line, at most 60 characters).

### desk.yaml

The desk's settings. A key or section left out stays as it is on the desk. Sections: \`ai\`
(\`enabled\`, \`model\`, \`models\`, \`monthlyReplyCap\`), \`chat\` (the chat widget: \`name\`, \`color\`,
\`mode\` (island or window), \`greetingCard\`, \`theme\`, \`greeting\`, \`suggestedQuestions\`,
\`allowedWebsites\`, \`openers\`, …),
\`hours\` (\`enabled\`, \`timeZone\`, \`days\`, \`awayMessage\`), \`inbox\` (\`assignment\`: \`mode\`,
\`capacity\`). Check the full key list in the docs before adding a key.`;

